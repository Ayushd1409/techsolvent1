export async function getAllRoutes() {
  const routes = [...staticRoutes];
  let blogs = [];

  try {
    const res = await fetch("https://techsolvent.techsolvent.cloud/api/blogs");
    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data) && data.length > 0) {
        blogs = data;
      }
    }
  } catch {
    // ignore, fall back
  }

  if (blogs.length === 0) {
    blogs = fallbackBlogPosts;
  }

  for (const blog of blogs) {
    const target = blog.slug || blog.id;
    if (!target) continue;

    const postTitle = blog.metaTitle || `${blog.title} | TechSolvent`;
    const postDesc = blog.metaDescription || blog.excerpt || (blog.content ? blog.content.replace(/<[^>]+>/g, "").slice(0, 160) : "");
    const canonical = blog.canonicalUrl || `https://techsolvent.in/blog/${target}`;

    routes.push({
      path: `/blog/${target}`,
      title: postTitle,
      description: postDesc,
      keywords: "blog, ai marketing, digital marketing insights, techsolvent",
      canonical: canonical,
      h1: blog.title,
      changefreq: "weekly",
      priority: "0.8",
      lastmod: blog.updatedAt ? new Date(blog.updatedAt).toISOString().split("T")[0] : new Date().toISOString().split("T")[0]
    });
  }

  return routes;
}
